-- 공공시설 예약 시스템 DDL (Oracle 21c XE, 스키마 FCLTY)
-- 컬럼명은 공공데이터 공통표준용어 약어를 따른다 (SN 일련번호, DE 일자, DT 일시, CD 코드, YN 여부 ...)

CREATE TABLE TB_MBER (
    MBER_ID        VARCHAR2(20)   NOT NULL,
    PASSWORD       VARCHAR2(100)  NOT NULL,          -- BCrypt 해시
    MBER_NM        VARCHAR2(50)   NOT NULL,
    AUTHOR_CD      VARCHAR2(20)   NOT NULL,          -- ROLE_USER / ROLE_ADMIN
    USE_YN         CHAR(1)        DEFAULT 'Y' NOT NULL,
    REGIST_DT      DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_MBER PRIMARY KEY (MBER_ID)
);

CREATE TABLE TB_CMMN_CODE (
    CODE_ID        VARCHAR2(20)   NOT NULL,
    CODE           VARCHAR2(20)   NOT NULL,
    CODE_NM        VARCHAR2(100)  NOT NULL,
    SORT_ORDR      NUMBER(3)      DEFAULT 1 NOT NULL,
    USE_YN         CHAR(1)        DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CMMN_CODE PRIMARY KEY (CODE_ID, CODE)
);

CREATE TABLE TB_FCLTY (
    FCLTY_SN        NUMBER(10)     NOT NULL,
    FCLTY_TY_CD     VARCHAR2(20)   NOT NULL,         -- 공통코드 FCLTY_TY
    FCLTY_NM        VARCHAR2(100)  NOT NULL,
    ADRES           VARCHAR2(200)  NOT NULL,
    ACMD_NMPR       NUMBER(5)      NOT NULL,         -- 수용인원
    OPER_BEGIN_TM   CHAR(4)        NOT NULL,         -- HH24MI
    OPER_END_TM     CHAR(4)        NOT NULL,
    RESVE_UNIT_MIN  NUMBER(3)      DEFAULT 60 NOT NULL,
    FCLTY_DC        VARCHAR2(2000),
    USE_YN          CHAR(1)        DEFAULT 'Y' NOT NULL,
    REGISTER_ID     VARCHAR2(20)   NOT NULL,
    REGIST_DT       DATE           DEFAULT SYSDATE NOT NULL,
    UPDUSR_ID       VARCHAR2(20),
    UPDT_DT         DATE,
    CONSTRAINT PK_FCLTY PRIMARY KEY (FCLTY_SN),
    CONSTRAINT CK_FCLTY_OPER CHECK (OPER_BEGIN_TM < OPER_END_TM)
);

-- SR-03: 시설 휴관일 (하루 단위). 같은 시설·같은 날은 한 번만 등록
CREATE TABLE TB_FCLTY_CLOSE (
    CLOSE_SN        NUMBER(10)     NOT NULL,
    FCLTY_SN        NUMBER(10)     NOT NULL,
    CLOSE_DE        CHAR(8)        NOT NULL,         -- YYYYMMDD
    CLOSE_RSN       VARCHAR2(300)  NOT NULL,         -- 100자 (한글 3바이트 기준)
    REGISTER_ID     VARCHAR2(20)   NOT NULL,
    REGIST_DT       DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_FCLTY_CLOSE PRIMARY KEY (CLOSE_SN),
    CONSTRAINT FK_CLOSE_FCLTY FOREIGN KEY (FCLTY_SN) REFERENCES TB_FCLTY (FCLTY_SN),
    CONSTRAINT UK_FCLTY_CLOSE UNIQUE (FCLTY_SN, CLOSE_DE)
);

CREATE TABLE TB_RESVE (
    RESVE_SN        NUMBER(12)     NOT NULL,
    FCLTY_SN        NUMBER(10)     NOT NULL,
    MBER_ID         VARCHAR2(20)   NOT NULL,
    RESVE_DE        CHAR(8)        NOT NULL,         -- YYYYMMDD
    BEGIN_TM        CHAR(4)        NOT NULL,         -- HH24MI
    END_TM          CHAR(4)        NOT NULL,
    USE_NMPR        NUMBER(5)      NOT NULL,
    USE_PURPS       VARCHAR2(600)  NOT NULL,
    RESVE_STTUS_CD  VARCHAR2(2)    NOT NULL,         -- 공통코드 RESVE_STTUS
    RETURN_RSN      VARCHAR2(1500),
    REGIST_DT       DATE           DEFAULT SYSDATE NOT NULL,
    UPDUSR_ID       VARCHAR2(20),
    UPDT_DT         DATE,
    CONSTRAINT PK_RESVE PRIMARY KEY (RESVE_SN),
    CONSTRAINT FK_RESVE_FCLTY FOREIGN KEY (FCLTY_SN) REFERENCES TB_FCLTY (FCLTY_SN),
    CONSTRAINT FK_RESVE_MBER  FOREIGN KEY (MBER_ID)  REFERENCES TB_MBER (MBER_ID),
    CONSTRAINT CK_RESVE_TM CHECK (BEGIN_TM < END_TM)
);
-- 겹침 검사(시설+일자), 1인 일일 한도(회원+일자) 조회용
CREATE INDEX IX_RESVE_FCLTY_DE ON TB_RESVE (FCLTY_SN, RESVE_DE);
CREATE INDEX IX_RESVE_MBER_DE  ON TB_RESVE (MBER_ID, RESVE_DE);

CREATE TABLE TB_RESVE_HIST (
    HIST_SN         NUMBER(12)     NOT NULL,
    RESVE_SN        NUMBER(12)     NOT NULL,
    BFR_STTUS_CD    VARCHAR2(2),                     -- 최초 신청은 NULL
    AFT_STTUS_CD    VARCHAR2(2)    NOT NULL,
    CHANGE_RSN      VARCHAR2(1500),
    CHANGER_ID      VARCHAR2(20)   NOT NULL,
    CHANGE_DT       DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_RESVE_HIST PRIMARY KEY (HIST_SN),
    CONSTRAINT FK_HIST_RESVE FOREIGN KEY (RESVE_SN) REFERENCES TB_RESVE (RESVE_SN)
);
CREATE INDEX IX_HIST_RESVE ON TB_RESVE_HIST (RESVE_SN);

CREATE TABLE TB_NOTICE (
    NTT_SN          NUMBER(10)     NOT NULL,
    NTT_SJ          VARCHAR2(300)  NOT NULL,
    NTT_CN          CLOB           NOT NULL,
    RDCNT           NUMBER(10)     DEFAULT 0 NOT NULL,
    USE_YN          CHAR(1)        DEFAULT 'Y' NOT NULL,
    REGISTER_ID     VARCHAR2(20)   NOT NULL,
    REGIST_DT       DATE           DEFAULT SYSDATE NOT NULL,
    UPDUSR_ID       VARCHAR2(20),
    UPDT_DT         DATE,
    CONSTRAINT PK_NOTICE PRIMARY KEY (NTT_SN)
);

CREATE SEQUENCE SEQ_FCLTY      START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_RESVE      START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_RESVE_HIST START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_NOTICE     START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_FCLTY_CLOSE START WITH 1 INCREMENT BY 1;
